import { describe, expect, it } from "vitest";
import { date, dateRange, rng, shortDates } from "./format";

describe("rng: טווח משמאל לימין", () => {
  it("עוטף בבידוד LTR כך שהקטן משמאל", () => {
    expect(rng(18, 27)).toBe("⁦18–27⁩");
    expect(rng("46", "58")).toBe("⁦46–58⁩");
  });
  it("תאריכים: טווח ימים באותו בידוד", () => {
    expect(dateRange("2026-09-30", "2026-10-01")).toBe("⁦30/9–1/10⁩");
    expect(dateRange("2026-10-01", "2026-10-01")).toBe("1/10");
  });
});

describe("date: תאריך אחד בכל האתר, יום/חודש (הכרעת בעלים 11.10.2026)", () => {
  it("בשנת הבחירות — בלי שנה ובלי אפס מוביל", () => {
    expect(date("2026-10-08")).toBe("8/10");
    expect(date("2026-09-09")).toBe("9/9");
    expect(date("2026-10-27T12:00:00+02:00")).toBe("27/10");
  });
  it("שנה אחרת — עם שנה, כדי שלא יהיה דו-משמעי", () => {
    expect(date("2022-11-01")).toBe("1/11/2022");
    expect(date("2025-12-31")).toBe("31/12/2025");
  });
  it("תאריך עם שעה נקבע לפי שעון ישראל", () => {
    expect(date("2026-10-08T22:30:00Z")).toBe("9/10");
  });
  it("תאריך בטקסט חופשי (ציטוט מקור)", () => {
    expect(shortDates("ynet, 10.9.2026; לפני 30.6.2024")).toBe("ynet, 10/9; לפני 30/6/2024");
  });
});
